#!/usr/bin/env python3
"""Generates Donut's icons from one design: a donut clock.

A thick ring holding the day's plan as coloured arcs (with a gap of free
time), and white hands at 10:10 in the hole, on a deep night background.

Writes:
  assets/icon/donut.svg, donut-512.png         master (app, Linux)
  android/.../drawable/ic_launcher_foreground.xml, ic_launcher_monochrome.xml
  android/.../mipmap-anydpi-v26/ic_launcher.xml  adaptive + themed icon
  android/.../mipmap-*/ic_launcher.png           pre-Android-8 launchers
  android/.../drawable/ic_stat_donut.xml         notification icon
  windows/runner/resources/app_icon.ico

Needs rsvg-convert and ImageMagick. Run from the repo root:
  python3 tool/make_icons.py
"""

import math
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

BACKGROUND = "#201A2B"
TRACK = "#3A3150"
INK = "#FFF6FA"
RED = "#FF4D5E"

# Adaptive icons are 108 units with a 66-unit safe circle in the middle.
C = 54.0
RING_R = 23.5
RING_W = 11.0
# (from°, to°, colour), clockwise from 12 o'clock; 272°–304° is left free.
ARCS = [
    (-56, 76, "#FF6FA8"),
    (84, 142, "#FFC24B"),
    (150, 222, "#36D1BE"),
    (230, 272, "#9C8CFF"),
]
# Hands at 10:10.
HOUR = ((10 + 10 / 60) / 12 * 360, 9.5, 3.4)
MINUTE = (10 / 60 * 360, 14.5, 2.6)


def point(deg, r, c=C):
    a = math.radians(deg)
    return c + r * math.sin(a), c - r * math.cos(a)


def arc_path(start, end, r, c=C):
    x0, y0 = point(start, r, c)
    x1, y1 = point(end, r, c)
    large = 1 if end - start > 180 else 0
    return f"M{x0:.3f},{y0:.3f} A{r},{r} 0 {large} 1 {x1:.3f},{y1:.3f}"


def hand_path(deg, length, c=C):
    x, y = point(deg, length, c)
    tx, ty = point(deg + 180, 0.6, c)
    return f"M{tx:.3f},{ty:.3f} L{x:.3f},{y:.3f}"


def dot_path(r, c=C):
    return f"M{c - r:.3f},{c:.3f} a{r},{r} 0 1,1 {2 * r:.3f},0 a{r},{r} 0 1,1 {-2 * r:.3f},0"


# ── Android vector drawables ────────────────────────────────────────────


def vector(paths, size_dp=108, viewport=108):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}
</vector>
"""


def stroke(d, color, width, cap="butt"):
    return f"""    <path
        android:pathData="{d}"
        android:strokeColor="{color}"
        android:strokeWidth="{width}"
        android:strokeLineCap="{cap}" />"""


def fill(d, color):
    return f'    <path android:fillColor="{color}" android:pathData="{d}" />'


def mark(colored=True, track=True, ink=INK, c=C, scale=1.0):
    """The ring, arcs and hands as vector paths."""
    r, w = RING_R * scale, RING_W * scale
    paths = []
    if track:
        paths.append(stroke(arc_path(0, 359.99, r, c), TRACK, w))
    for start, end, color in ARCS:
        paths.append(stroke(arc_path(start, end, r, c), color if colored else ink, w))
    for deg, length, width in (HOUR, MINUTE):
        paths.append(stroke(hand_path(deg, length * scale, c), ink, width * scale, "round"))
    paths.append(fill(dot_path(2.4 * scale, c), ink))
    if colored:
        paths.append(fill(dot_path(1.1 * scale, c), RED))
    return paths


# ── SVG (for PNGs and the desktop) ──────────────────────────────────────


def svg(size=1024, background="circle"):
    s = size / 108
    parts = []
    if background == "circle":
        parts.append(f'<circle cx="54" cy="54" r="50" fill="{BACKGROUND}"/>')
    elif background == "full":
        parts.append(f'<rect width="108" height="108" fill="{BACKGROUND}"/>')
    # The mark fills more of a plain circle than of the adaptive safe zone.
    k = 1.42 if background == "circle" else 1.0
    g = f'<g transform="translate(54 54) scale({k}) translate(-54 -54)">'
    g += f'<path d="{arc_path(0, 359.99, RING_R)}" stroke="{TRACK}" stroke-width="{RING_W}" fill="none"/>'
    for start, end, color in ARCS:
        g += f'<path d="{arc_path(start, end, RING_R)}" stroke="{color}" stroke-width="{RING_W}" fill="none"/>'
    for deg, length, width in (HOUR, MINUTE):
        g += (
            f'<path d="{hand_path(deg, length)}" stroke="{INK}" stroke-width="{width}" '
            'stroke-linecap="round" fill="none"/>'
        )
    g += f'<circle cx="54" cy="54" r="2.4" fill="{INK}"/><circle cx="54" cy="54" r="1.1" fill="{RED}"/>'
    g += "</g>"
    parts.append(g)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 108 108">{"".join(parts)}</svg>\n'
    )


def render(svg_text, out, size):
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg_text)
    subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(out), f.name],
        check=True,
    )
    Path(f.name).unlink()


def main():
    icon_dir = ROOT / "assets/icon"
    icon_dir.mkdir(parents=True, exist_ok=True)
    master = svg(1024, "circle")
    (icon_dir / "donut.svg").write_text(master)
    render(master, icon_dir / "donut-512.png", 512)

    drawable = RES / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(vector(mark()))
    (drawable / "ic_launcher_monochrome.xml").write_text(
        vector(mark(colored=False, track=False))
    )
    # Status-bar icon: white shapes on transparent, 24dp.
    (drawable / "ic_stat_donut.xml").write_text(
        vector(mark(colored=False, track=False, ink="#FFFFFF", c=12, scale=0.42), 24, 24)
    )
    values = RES / "values"
    (values / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
"""
    )
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    )
    for density, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        render(master, RES / f"mipmap-{density}/ic_launcher.png", px)

    with tempfile.TemporaryDirectory() as tmp:
        pngs = []
        for px in (16, 24, 32, 48, 64, 128, 256):
            out = Path(tmp) / f"{px}.png"
            render(master, out, px)
            pngs.append(str(out))
        subprocess.run(
            ["magick", *pngs, str(ROOT / "windows/runner/resources/app_icon.ico")],
            check=True,
        )
    print("icons written")


if __name__ == "__main__":
    main()
